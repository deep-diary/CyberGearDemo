Triangle_t SinCos(uint32_t theta)
{
  Triangle_t sinCos;
  uint16_t   index    = theta >> TRIAG_MANTISSA_Q;
  uint32_t   mantissa = theta - (index << TRIAG_MANTISSA_Q);
  uint16_t   sinIndex = index & TRIAG_TABLE_INDEX_MASK;
  /* divide 4, means 90 degree*/
  uint16_t   cosIndex = (index + (1UL << (TRIAG_TABLE_SIZE_SHIFT - 2))) & TRIAG_TABLE_INDEX_MASK;

  int32_t sinInterp = (int32_t)(SIN_TABLE[sinIndex + 1] - SIN_TABLE[sinIndex]) * mantissa;
  sinCos._sin       = SIN_TABLE[sinIndex] + (int16_t)(sinInterp >> TRIAG_MANTISSA_Q);

  int32_t cosInterp = (int32_t)(SIN_TABLE[cosIndex + 1] - SIN_TABLE[cosIndex]) * mantissa;
  sinCos._cos       = SIN_TABLE[cosIndex] + (int16_t)(cosInterp >> TRIAG_MANTISSA_Q);

  return sinCos;
}